/** Запускает скрипт и возвращает пойманную ошибку исполнения. */
function execThrows(source: string, options?: RunOptions): Error {
  try {
    run(source, createGlobalContext(), options);
  } catch (error) {
    if (error instanceof Error) return error;
    throw new Error(`Ожидалась Error, получено: ${String(error)}`);
  }
  throw new Error('Ожидалась ошибка исполнения');
}

/** Запускает скрипт и возвращает снимок ошибки (обязательно есть). */
function execSnapshot(source: string, options?: RunOptions): ErrorSnapshot {
  const snapshot = getErrorSnapshot(execThrows(source, options));
  if (!snapshot) throw new Error('У ошибки нет снимка');
  return snapshot;
}

/** Запускает скрипт и собирает `Сообщить()` (console.log). */
function execLogs(source: string, options?: RunOptions): string[] {
  const logs: string[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(String(args[0]));
  });
  try {
    run(source, createGlobalContext(), options);
  } finally {
    spy.mockRestore();
  }
  return logs;
}

/** Запуск главного скрипта с картой импортируемых исходников. */
function execWithModules(mainSource: string, entries: Record<string, string>, mainPath = '/app/main.osjs'): Error {
  return execThrows(mainSource, {
    path: mainPath,
    sourceId: mainPath,
    basePath: mainPath,
    modules: new Map(Object.entries(entries)),
    resolve: defaultResolve,
  });
}

