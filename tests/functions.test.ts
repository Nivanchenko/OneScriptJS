import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

/** Выполняет исходник и собирает аргументы console.log (реальный Сообщить). */
function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('процедуры и функции', () => {
  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('вызывает функцию и печатает результат', () => {
    expect(
      exec('Функция Сложить(А, Б)\n  Возврат А + Б;\nКонецФункции\nсообщить(Сложить(2, 3));'),
    ).toEqual(['5']);
  });

  it('вызывает процедуру (без возврата значения)', () => {
    expect(
      exec('Процедура Поприветствовать(Имя)\n  сообщить("Привет, " + Имя);\nКонецПроцедуры\nПоприветствовать("Никита");'),
    ).toEqual(['Привет, Никита']);
  });

  it('поддерживает значения параметров по умолчанию', () => {
    expect(
      exec('Функция Привет(Имя = "Мир")\n  Возврат "Привет, " + Имя;\nКонецФункции\nсообщить(Привет()); сообщить(Привет("Ты"));'),
    ).toEqual(['Привет, Мир', 'Привет, Ты']);
  });

  it('локальные переменные не утекают наружу', () => {
    expect(
      exec('Функция Ф()\n  Внутри = 1;\n  Возврат Внутри;\nКонецФункции\nсообщить(Ф()); сообщить(Внутри);'),
    ).toEqual(['1', '']);
  });

  it('модульные переменные (Перем) разделяются между функциями', () => {
    expect(
      exec(
        'Перем Счётчик;\n' +
          'Функция Увеличить()\n  Счётчик = Счётчик + 1;\n  Возврат Счётчик;\nКонецФункции\n' +
          'Счётчик = 0;\nсообщить(Увеличить()); сообщить(Увеличить());',
      ),
    ).toEqual(['1', '2']);
  });

  it('поддерживает рекурсию', () => {
    expect(
      exec(
        'Функция Факториал(Н)\n  Если Н <= 1 Тогда\n    Возврат 1;\n  КонецЕсли;\n  Возврат Н * Факториал(Н - 1);\nКонецФункции\nсообщить(Факториал(5));',
      ),
    ).toEqual(['120']);
  });
});
