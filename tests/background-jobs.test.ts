import { describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';
import { isThenable } from '../src/runtime/async';

/** Запускает BSL-скрипт, дожидается фоновых заданий и возвращает вывод `Сообщить`. */
async function execute(source: string): Promise<string[]> {
  const logs: string[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(args.map((a) => String(a)).join(' '));
  });
  try {
    const returned = run(source, createGlobalContext());
    if (isThenable(returned)) await returned;
    return logs;
  } finally {
    spy.mockRestore();
  }
}

describe('фоновые задания: User Story 1', () => {
  it('выполняет функцию, возвращает результат и состояние', async () => {
    const logs = await execute(`
      Функция Посчитать(Знач Н) Экспорт
        Приостановить(10);
        Возврат Н * 2;
      КонецФункции

      Параметры = Новый Массив;
      Параметры.Добавить(21);
      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Посчитать", Параметры);
      Сообщить(Задание.ИмяМетода);
      Сообщить(Задание.Объект = ЭтотОбъект);
      Сообщить(Задание.Параметры.Количество());
      Задание.ОжидатьЗавершения();
      Сообщить(Задание.Состояние);
      Сообщить(Задание.Результат);
    `);
    expect(logs).toEqual(['Посчитать', 'Истина', '1', 'Завершено', '42']);
  });

  it('для процедуры результат — Неопределено', async () => {
    const logs = await execute(`
      Процедура Просто() Экспорт
        Приостановить(5);
      КонецПроцедуры

      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Просто");
      Задание.ОжидатьЗавершения();
      Сообщить(Задание.Состояние);
      Сообщить(Задание.Результат = Неопределено);
      Сообщить(Задание.Параметры = Неопределено);
    `);
    expect(logs).toEqual(['Завершено', 'Истина', 'Истина']);
  });

  it('основной скрипт продолжает работу, пока задание не завершилось', async () => {
    const logs = await execute(`
      Процедура Долго() Экспорт
        Приостановить(30);
        Сообщить("задание");
      КонецПроцедуры

      ФоновыеЗадания.Выполнить(ЭтотОбъект, "Долго");
      Сообщить("основной");
    `);
    // Задание стартует в ближайшем кванте, поэтому маркер основного скрипта — раньше.
    expect(logs).toEqual(['основной', 'задание']);
  });

  it('ошибка задания не бросается в ожидание, а попадает в ИнформацияОбОшибке', async () => {
    const logs = await execute(`
      Процедура Упасть() Экспорт
        Приостановить(5);
        ВызватьИсключение "Я ошибка в коде";
      КонецПроцедуры

      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Упасть");
      Сообщить(Задание.ОжидатьЗавершения());
      Сообщить(Задание.Состояние);
      Сообщить(Задание.ИнформацияОбОшибке.Описание);
      Сообщить(Задание.Результат = Неопределено);
    `);
    expect(logs).toEqual(['Истина', 'ЗавершеноАварийно', 'Я ошибка в коде', 'Истина']);
  });

  it('копирует массив параметров на момент запуска', async () => {
    const logs = await execute(`
      Функция Сумма(Знач А, Знач Б) Экспорт
        Приостановить(30);
        Возврат А + Б;
      КонецФункции

      Параметры = Новый Массив;
      Параметры.Добавить(1);
      Параметры.Добавить(2);
      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Сумма", Параметры);
      Параметры[0] = 100;
      Задание.ОжидатьЗавершения();
      Сообщить(Задание.Результат);
    `);
    expect(logs).toEqual(['3']);
  });

  it('неверные аргументы Выполнить дают понятные ошибки', async () => {
    const logs = await execute(`
      Процедура Просто() Экспорт
      КонецПроцедуры

      Попытка
        ФоновыеЗадания.Выполнить(Неопределено, "Метод");
        Сообщить("без ошибки");
      Исключение
        Сообщить("не объект");
      КонецПопытки;
      Попытка
        ФоновыеЗадания.Выполнить(ЭтотОбъект, "НетТакогоМетода");
        Сообщить("без ошибки");
      Исключение
        Сообщить("нет метода");
      КонецПопытки;
      Попытка
        ФоновыеЗадания.Выполнить(ЭтотОбъект, "Просто", "не массив");
        Сообщить("без ошибки");
      Исключение
        Сообщить("не массив");
      КонецПопытки;
    `);
    expect(logs).toEqual(['не объект', 'нет метода', 'не массив']);
  });

  it('ожидание уже завершённого задания возвращает Истина', async () => {
    const logs = await execute(`
      Процедура Быстро() Экспорт
      КонецПроцедуры

      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Быстро");
      Задание.ОжидатьЗавершения();
      Сообщить(Задание.ОжидатьЗавершения());
      Сообщить(Задание.Состояние);
    `);
    expect(logs).toEqual(['Истина', 'Завершено']);
  });
});
