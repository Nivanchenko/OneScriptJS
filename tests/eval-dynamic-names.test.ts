import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

afterEach(() => vi.restoreAllMocks());

describe('динамические имена: US1 — окружение вызывающего', () => {
  it('Выполнить меняет локальную переменную вызывающего', () => {
    expect(exec('Рез = 1; Выполнить "Рез = Рез + 3"; Сообщить(Рез);')).toEqual(['4']);
  });

  it('Выполнить меняет параметр процедуры', () => {
    expect(
      exec('Процедура Ф(Пар)\n  Выполнить "Пар = Пар + 1";\n  Сообщить(Пар);\nКонецПроцедуры\nФ(1);'),
    ).toEqual(['2']);
  });

  it('имя из фрагмента не видно следующему фрагменту', () => {
    expect(
      exec(
        'Выполнить "Т = 5";\n' +
          'Попытка\n  Выполнить "Сообщить(Т)";\nИсключение\n  Сообщить("ошибка: " + ОписаниеОшибки());\nКонецПопытки;',
      ),
    ).toEqual(['ошибка: Неизвестный символ: Т']);
  });

  it('имя из фрагмента не видно методу модуля', () => {
    expect(
      exec(
        'Функция ПрочитатьТ()\n  Возврат Т;\nКонецФункции\n' +
          'Выполнить "Т = 5";\nСообщить(ПрочитатьТ() = Неопределено);',
      ),
    ).toEqual(['Истина']);
  });

  it('вложенный Выполнить внутри Исключение видит локальную объемлющего', () => {
    expect(
      exec(
        'Рез = 1;\n' +
          'Выполнить "Попытка\n' +
          '|  ВызватьИсключение 1;\n' +
          '|Исключение\n' +
          '|  Выполнить ""Рез = Рез + 2"";\n' +
          '|КонецПопытки;";\n' +
          'Сообщить(Рез);',
      ),
    ).toEqual(['3']);
  });

  it('Вычислить видит локальные, параметры и модульные переменные', () => {
    // объявления методов обязаны идти до исполняемого кода — блок Ф переставлен вверх
    expect(
      exec(
        'Перем М;\n' +
          'Функция Ф(П)\n  Возврат Вычислить("М + П + Л");\nКонецФункции\n' +
          'М = 10;\nЛ = 1;\nСообщить(Ф(2));',
      ),
    ).toEqual(['13']);
  });
});

describe('динамические имена: US2 — ошибка до исполнения', () => {
  it('неизвестное имя — ошибка до исполнения, без побочных эффектов', () => {
    expect(
      exec(
        'Попытка\n  Выполнить "Сообщить(""до""); Х = Х + 1;";\n' +
          'Исключение\n  Сообщить("поймано");\nКонецПопытки;',
      ),
    ).toEqual(['поймано']);
  });

  it('ошибка ловится Попыткой и видна в ОписаниеОшибки и ИнформацияОбОшибке', () => {
    expect(
      exec(
        'Попытка\n  Выполнить "НетТакого = НетТакого + 1";\nИсключение\n' +
          '  Сообщить(ОписаниеОшибки());\n  Сообщить(ИнформацияОбОшибке().Описание);\nКонецПопытки;',
      ),
    ).toEqual(['Неизвестный символ: НетТакого', 'Неизвестный символ: НетТакого']);
  });

  it('последовательное разрешение: присваивание раньше чтения', () => {
    expect(exec('Выполнить "Новое = 5; Новое = Новое + 8; Сообщить(Новое);";')).toEqual(['13']);
  });

  it('присваивание в ветке Если разрешает последующее чтение', () => {
    expect(exec('Выполнить "Если Истина Тогда В = 1; КонецЕсли; Сообщить(В);";')).toEqual(['1']);
  });

  it('внутренняя Попытка динамического текста не срабатывает при ошибке разрешения', () => {
    expect(
      exec(
        'Попытка\n  Выполнить "Попытка Сообщить(""внутри""); Х = Х + 1; ' +
          'Исключение Сообщить(""внутренняя""); КонецПопытки;";\n' +
          'Исключение\n  Сообщить("внешняя");\nКонецПопытки;',
      ),
    ).toEqual(['внешняя']);
  });

  it('неизвестная функция — Неизвестный символ', () => {
    expect(
      exec('Попытка\n  Выполнить "Упс()";\nИсключение\n  Сообщить(ОписаниеОшибки());\nКонецПопытки;'),
    ).toEqual(['Неизвестный символ: Упс']);
  });

  it('Вычислить с неизвестным именем — ошибка', () => {
    expect(
      exec(
        'Попытка\n  Вычислить("НетТакой + 1");\nИсключение\n  Сообщить(ОписаниеОшибки());\nКонецПопытки;',
      ),
    ).toEqual(['Неизвестный символ: НетТакой']);
  });

  it('статический код сохраняет Неопределено (FR-008)', () => {
    expect(exec('Сообщить(НетТакой = Неопределено);')).toEqual(['Истина']);
  });

  it('эталон: ТестДолжен_ПроверитьВызовыВыполнитьСПопытками → 0134567+', () => {
    const source = `Процедура СИсключением()
  Выполнить "
  |Попытка
  |  Рез = Рез + 8;
  |  ВызватьИсключение 0;
  |Исключение
  |  Рез = Рез + 9;
  |КонецПопытки;
  |Выполнить(""Рез = Рез + (-10)"");";
КонецПроцедуры

Процедура Тест()
  Рез = "0";
  Попытка
    Выполнить("
      |Лок=""1"";
      |Попытка
      |  Рез = 1/0;
      |Исключение
      |  Рез = Рез + Лок;
      |КонецПопытки;");
    Выполнить("
      |Попытка
      |  Рез = Рез + 2/0;
      |Исключение
      |  Выполнить(""Рез = Рез + 3"");
      |КонецПопытки;
      |Рез = Рез + 4;");
    Выполнить("
      |Попытка
      |  Рез = Рез + 5;
      |  СИсключением();
      |Исключение
      |  Рез = Рез + 6;
      |КонецПопытки;
      |Рез = Рез + 7;");
  Исключение
    Рез = Рез + "!";
  КонецПопытки;
  Рез = Рез + "+";
  Сообщить(Рез);
КонецПроцедуры

Тест();`;

    expect(exec(source)).toEqual(['0134567+']);
  });
});

describe('динамические имена: лексические локальные вызывающего (регрессия ревью)', () => {
  it('Перем без присваивания видна динамическому коду как Неопределено', () => {
    expect(
      exec('Процедура П()\n  Перем Л;\n  Выполнить "Сообщить(Л = Неопределено)";\nКонецПроцедуры\nП();'),
    ).toEqual(['Истина']);
  });

  it('локаль, присвоенная позже в вызывающем, видна динамическому коду', () => {
    expect(
      exec(
        'Процедура П()\n  Выполнить "Сообщить(Л = Неопределено)";\n  Л = 1;\nКонецПроцедуры\nП();',
      ),
    ).toEqual(['Истина']);
  });

  it('присваивание только в неисполненной ветке — имя всё равно локаль вызывающего', () => {
    expect(
      exec(
        'Процедура П(Флаг)\n  Если Флаг Тогда Л = 1; КонецЕсли;\n' +
          '  Выполнить "Сообщить(Л = Неопределено)";\nКонецПроцедуры\nП(Ложь);',
      ),
    ).toEqual(['Истина']);
  });

  it('модульный уровень: локаль, присвоенная позже, видна динамическому коду', () => {
    expect(exec('Выполнить "Сообщить(Л = Неопределено)";\nЛ = 1;')).toEqual(['Истина']);
  });

  it('динамический код МЕНЯЕТ объявленную локальную переменную вызывающего (FR-001)', () => {
    expect(
      exec('Процедура П()\n  Перем Л;\n  Выполнить "Л = 7";\n  Сообщить(Л);\nКонецПроцедуры\nП();'),
    ).toEqual(['7']);
  });

  it('Вычислить видит лексическую локаль вызывающего до присваивания', () => {
    expect(
      exec(
        'Процедура П()\n  Сообщить(Вычислить("Л = Неопределено"));\n  Л = 1;\nКонецПроцедуры\nП();',
      ),
    ).toEqual(['Истина']);
  });

  it('переменная цикла вызывающего видна динамическому коду до цикла', () => {
    expect(
      exec('Выполнить "Сообщить(Сч = Неопределено)";\nДля Сч = 1 По 1 Цикл КонецЦикла;'),
    ).toEqual(['Истина']);
  });

  it('вложенный фрагмент видит имя объемлющего фрагмента до присваивания (как слот эталона)', () => {
    expect(
      exec('Выполнить "Выполнить ""Сообщить(А = Неопределено)""; А = 1;";'),
    ).toEqual(['Истина']);
  });
});
