import { describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';
import { isThenable } from '../src/runtime/async';

/**
 * Адаптация `reference/OneScript/tests/tasks.os` к кооперативной модели.
 *
 * Воспроизведены сценарии, не требующие настоящих потоков: создание, поиск, ожидания,
 * результат/ошибка, текущее задание, события и перечисления в заданиях, `Очистить`,
 * вложенный запуск задания. Исключены (требуют потоков): `ТекущийПоток`, `БлокировкаРесурса`,
 * изоляция данных потока, обработчики завершения потока, файловые ресурсы, дочерние процессы,
 * «параллельные» гонки.
 */

async function execute(source: string): Promise<string[]> {
  const logs: string[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(args.map((a) => String(a)).join(' '));
  });
  try {
    const returned = run(source, createGlobalContext());
    if (isThenable(returned)) await returned;
    return logs;
  } finally {
    spy.mockRestore();
  }
}

