import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('ТаблицаЗначений', () => {
  afterEach(() => vi.restoreAllMocks());

  it('добавляет колонки и строки, доступ по имени', () => {
    expect(
      exec('Т = Новый ТаблицаЗначений; Т.Колонки.Добавить("К1"); Т.Колонки.Добавить("К2"); С = Т.Добавить(); С.К1 = 10; С.К2 = 20; сообщить(Т.Количество()); сообщить(С.К1); сообщить(С[1]);'),
    ).toEqual(['1', '10', '20']);
  });

  it('Найти и НайтиСтроки по колонке', () => {
    expect(
      exec('Т = Новый ТаблицаЗначений; Т.Колонки.Добавить("К1"); Т.Добавить().К1 = 1; Т.Добавить().К1 = 2; сообщить(Т.Найти(2).К1); Ф = Новый Структура("К1", 1); сообщить(Т.НайтиСтроки(Ф).Количество());'),
    ).toEqual(['2', '1']);
  });

  it('Сортировать по колонке (возр/убыв)', () => {
    expect(
      exec('Т = Новый ТаблицаЗначений; Т.Колонки.Добавить("К1"); Т.Добавить().К1 = 3; Т.Добавить().К1 = 1; Т.Добавить().К1 = 2; Т.Сортировать("К1"); сообщить(Т[0].К1); Т.Сортировать("К1 УБЫВ"); сообщить(Т[0].К1);'),
    ).toEqual(['1', '3']);
  });

  it('Итог и ВыгрузитьКолонку', () => {
    expect(
      exec('Т = Новый ТаблицаЗначений; Т.Колонки.Добавить("К1"); Т.Добавить().К1 = 10; Т.Добавить().К1 = 20; сообщить(Т.Итог("К1")); М = Т.ВыгрузитьКолонку("К1"); сообщить(М[1]);'),
    ).toEqual(['30', '20']);
  });

  it('Свернуть группирует и суммирует', () => {
    expect(
      exec('Т = Новый ТаблицаЗначений; Т.Колонки.Добавить("Ключ"); Т.Колонки.Добавить("Значение"); С = Т.Добавить(); С.Ключ = "а"; С.Значение = 1; С = Т.Добавить(); С.Ключ = "а"; С.Значение = 2; Т.Свернуть("Ключ", "Значение"); сообщить(Т.Количество()); сообщить(Т[0].Значение);'),
    ).toEqual(['1', '3']);
  });
});
