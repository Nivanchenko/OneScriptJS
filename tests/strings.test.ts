import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('строковые функции', () => {
  afterEach(() => vi.restoreAllMocks());

  it('Строка/Число (конвертация)', () => {
    expect(exec('сообщить(Строка(42)); сообщить(Число("42") + 1);')).toEqual(['42', '43']);
  });

  it('СтрДлина', () => {
    expect(exec('сообщить(СтрДлина("Привет"));')).toEqual(['6']);
  });

  it('ВРег/НРег', () => {
    expect(exec('сообщить(ВРег("abc")); сообщить(НРег("ABC"));')).toEqual(['ABC', 'abc']);
  });

  it('Лев/Прав/Сред', () => {
    expect(exec('сообщить(Лев("Привет", 3)); сообщить(Прав("Привет", 2)); сообщить(Сред("Привет", 2, 3));')).toEqual([
      'При',
      'ет',
      'рив',
    ]);
  });

  it('Найти (1-базовый, 0 если не найден)', () => {
    expect(exec('сообщить(Найти("Привет", "и")); сообщить(Найти("Привет", "z"));')).toEqual(['3', '0']);
  });

  it('СтрЗаменить', () => {
    expect(exec('сообщить(СтрЗаменить("a-b-c", "-", "+"));')).toEqual(['a+b+c']);
  });

  it('СтрЧислоВхождений', () => {
    expect(exec('сообщить(СтрЧислоВхождений("aaa", "a"));')).toEqual(['3']);
  });

  it('СтрНачинаетсяС/СтрЗаканчиваетсяНа', () => {
    expect(exec('сообщить(СтрНачинаетсяС("Привет", "При")); сообщить(СтрЗаканчиваетсяНа("Привет", "ет"));')).toEqual([
      'Истина',
      'Истина',
    ]);
  });

  it('СтрРазделить возвращает Массив', () => {
    expect(exec('М = СтрРазделить("a,b,c", ","); сообщить(М.Количество()); сообщить(М[1]);')).toEqual(['3', 'b']);
  });

  it('СтрСоединить объединяет массив', () => {
    expect(exec('М = Новый Массив; М.Добавить("a"); М.Добавить("b"); сообщить(СтрСоединить(М, "-"));')).toEqual(['a-b']);
  });

  it('Символ/КодСимвола', () => {
    expect(exec('сообщить(Символ(65)); сообщить(КодСимвола("A", 1));')).toEqual(['A', '65']);
  });

  it('ТРег', () => {
    expect(exec('сообщить(ТРег("привет мир"));')).toEqual(['Привет Мир']);
  });

  it('СтрЧислоСтрок и СтрПолучитьСтроку', () => {
    expect(exec('ПС = Символ(10); Т = "a" + ПС + "b" + ПС + "c"; сообщить(СтрЧислоСтрок(Т)); сообщить(СтрПолучитьСтроку(Т, 2));')).toEqual([
      '3',
      'b',
    ]);
  });

  it('СтрНайти', () => {
    expect(exec('сообщить(СтрНайти("Привет", "и"));')).toEqual(['3']);
  });

  it('СтрШаблон', () => {
    expect(exec('сообщить(СтрШаблон("Привет, %1!", "Мир"));')).toEqual(['Привет, Мир!']);
  });
});
