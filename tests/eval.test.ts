import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('динамическое исполнение: Вычислить / Выполнить', () => {
  afterEach(() => vi.restoreAllMocks());

  it('Вычислить: простое выражение и локальная переменная', () => {
    expect(exec('сообщить(Вычислить("2 + 2")); Внешняя = 1; сообщить(Вычислить("Внешняя"));')).toEqual(['4', '1']);
  });

  it('Вычислить видит локальные переменные метода', () => {
    expect(
      exec('Функция Ф()\n  Локальная = 1;\n  Возврат Вычислить("Локальная + 1");\nКонецФункции\nсообщить(Ф());'),
    ).toEqual(['2']);
  });

  it('Вычислить вызывает функции модуля', () => {
    expect(exec('Функция Хороший()\n  Возврат 5;\nКонецФункции\nсообщить(Вычислить("Хороший()"));')).toEqual(['5']);
  });

  it('Выполнить меняет локальные переменные', () => {
    expect(
      exec('ВнешнийКонтекст = "Привет"; Выполнить "ВнешнийКонтекст = ""Пока"""; сообщить(ВнешнийКонтекст);'),
    ).toEqual(['Пока']);
  });

  it('Выполнить с несколькими операторами', () => {
    expect(exec('А = 1; Выполнить "А = 2; А = А + 3;"; сообщить(А);')).toEqual(['5']);
  });

  it('Выполнить запрещает Возврат вне метода', () => {
    expect(() => exec('Выполнить "Возврат 1;";')).toThrow(/только внутри метода/);
  });

  it('Выполнить: исключение ловится Попыткой', () => {
    expect(
      exec('Рез = 1; Выполнить "Попытка Рез = 1/0; Исключение Рез = -1; КонецПопытки;"; сообщить(Рез);'),
    ).toEqual(['-1']);
  });

  it('Выполнить: вызов процедуры модуля', () => {
    expect(
      exec('Перем Глобал;\nПроцедура Внутр()\n  Глобал = 42;\nКонецПроцедуры\nГлобал = 0;\nВыполнить "Внутр();";\nсообщить(Глобал);'),
    ).toEqual(['42']);
  });

  it('Вычислить внутри Выполнить', () => {
    expect(exec('Рез = -1; Выполнить "ц = 5; Рез = Вычислить(""ц + 1"")"; сообщить(Рез);')).toEqual(['6']);
  });

  it('Выполнить работает с параметрами процедуры', () => {
    expect(
      exec(
        'Процедура ЗаменаПараметра(Пар)\n  Выполнить "Пар = Пар + 1";\nКонецПроцедуры\n' +
          'Рез = 1;\nВыполнить "ЗаменаПараметра(Рез);";\nсообщить(Рез);',
      ),
    ).toEqual(['2']);
  });

  it('Выполнить объявляет процедуры модуля', () => {
    expect(exec('Перем Глобал;\nВыполнить "Процедура П() Глобал = 7; КонецПроцедуры"; П(); сообщить(Глобал);')).toEqual(['7']);
  });

  it('Выполнить: Перем видна процедуре, объявленной в том же фрагменте', () => {
    expect(
      exec(
        'Выполнить "Перем Н;\n' +
          'Процедура ИзменитьН()\n  Н = 55;\nКонецПроцедуры\n' +
          'Н = 1;\nИзменитьН();\nСообщить(Н);";',
      ),
    ).toEqual(['55']);
  });

  it('Выполнить: Перем без присваивания видна процедуре', () => {
    expect(
      exec(
        'Выполнить "Перем Н;\n' +
          'Процедура ИзменитьН()\n  Н = 55;\nКонецПроцедуры\n' +
          'ИзменитьН();\nСообщить(Н);";',
      ),
    ).toEqual(['55']);
  });
});
