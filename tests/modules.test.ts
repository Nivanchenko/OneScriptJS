import { describe, expect, it } from 'vitest';
import { runWithModules } from './helpers/module-fixtures';

const MODULE = '/app/lib/Модуль.os';

describe('импорт модуля (#Использовать)', () => {
  it('делает доступными экспортные функцию и переменную', () => {
    const logs = runWithModules(
      [
        '#Использовать "lib/Модуль.os"',
        'Сообщить(Модуль.Сложить(1, 2));',
        'Модуль.Поле = 15;',
        'Сообщить(Модуль.Поле);',
      ].join('\n'),
      {
        [MODULE]: [
          'Перем Поле Экспорт;',
          'Функция Сложить(А, Б) Экспорт',
          '  Возврат А + Б;',
          'КонецФункции',
          'Поле = 10;',
          'Сообщить("модуль загружен");',
        ].join('\n'),
      },
    );
    expect(logs).toEqual(['модуль загружен', '3', '15']);
  });

  it('исполняет тело модуля ровно один раз и до кода главного скрипта', () => {
    const logs = runWithModules(
      [
        '#Использовать "lib/Модуль.os"',
        '#Использовать "lib/Модуль.os"',
        'Сообщить("main");',
      ].join('\n'),
      { [MODULE]: 'Сообщить("module");' },
    );
    expect(logs).toEqual(['module', 'main']);
  });

  it('не отдаёт наружу неэкспортные члены', () => {
    const entries = {
      [MODULE]: [
        'Перем Внутренняя;',
        'Процедура Скрытая()',
        'КонецПроцедуры',
        'Функция Открытая() Экспорт',
        '  Возврат 2;',
        'КонецФункции',
        'Внутренняя = 1;',
      ].join('\n'),
    };
    expect(() =>
      runWithModules('#Использовать "lib/Модуль.os"\nСообщить(Модуль.Скрытая());', entries),
    ).toThrow("Метод 'Скрытая' не найден");
    expect(() =>
      runWithModules('#Использовать "lib/Модуль.os"\nСообщить(Модуль.Внутренняя);', entries),
    ).toThrow("Свойство 'Внутренняя' не найдено");
    expect(
      runWithModules('#Использовать "lib/Модуль.os"\nСообщить(Модуль.Открытая());', entries),
    ).toEqual(['2']);
  });

  it('оставляет #Использовать asserts без загрузки файла', () => {
    const logs = runWithModules('#Использовать asserts\nСообщить("ok");');
    expect(logs).toEqual(['ok']);
  });

  it('разрешает путь от текущего файла', () => {
    const logs = runWithModules(
      '#Использовать "lib/Относительный.os"\nСообщить(Относительный.Имя);',
      { '/app/lib/Относительный.os': 'Перем Имя Экспорт;\nИмя = "рядом";' },
    );
    expect(logs).toEqual(['рядом']);
  });

  it('разрешает путь от корня', () => {
    const logs = runWithModules(
      '#Использовать "/lib/Корневой.os"\nСообщить(Корневой.Имя);',
      { '/lib/Корневой.os': 'Перем Имя Экспорт;\nИмя = "корень";' },
    );
    expect(logs).toEqual(['корень']);
  });

  it('сообщает о конфликте имён двух файлов', () => {
    expect(() =>
      runWithModules(
        '#Использовать "a/Модуль.os"\n#Использовать "b/Модуль.os"',
        { '/app/a/Модуль.os': 'Перем А;', '/app/b/Модуль.os': 'Перем Б;' },
      ),
    ).toThrow("Имя 'Модуль' уже занято");
  });

  it('сообщает о недопустимом имени файла', () => {
    expect(() =>
      runWithModules('#Использовать "lib/my-script.os"', {
        '/app/lib/my-script.os': 'Перем А;',
      }),
    ).toThrow('не является допустимым идентификатором');
  });

  it('сообщает об отсутствующем файле с директивой и строкой', () => {
    expect(() => runWithModules('#Использовать "lib/Нет.os"')).toThrow(
      "Файл не найден: '/app/lib/Нет.os' (директива #Использовать, строка 1)",
    );
  });

  it('оборачивает ошибку разбора вложенного файла его путём', () => {
    expect(() =>
      runWithModules('#Использовать "lib/Бад.os"', {
        '/app/lib/Бад.os': 'Функция Сломано(',
      }),
    ).toThrow("Ошибка в импортируемом файле '/app/lib/Бад.os'");
  });

  it('запрещает создавать модуль через Новый', () => {
    expect(() =>
      runWithModules('#Использовать "lib/Модуль.os"\nНовый Модуль;', {
        [MODULE]: 'Перем А;',
      }),
    ).toThrow("Модуль 'Модуль' не является классом");
  });
});
