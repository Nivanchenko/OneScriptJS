import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('сценарии', () => {
  afterEach(() => vi.restoreAllMocks());

  it('ЗагрузитьСценарийИзСтроки возвращает тип Сценарий', () => {
    expect(
      exec(
        'С = ЗагрузитьСценарийИзСтроки("Перем Привет;"); ' +
          'сообщить(Тип("Сценарий") = ТипЗнч(С)); сообщить(Строка(С));',
      ),
    ).toEqual(['Истина', 'Сценарий']);
  });

  it('Строка(Сценарий) использует ОбработкаПолученияПредставления', () => {
    expect(
      exec(
        'Текст = "Процедура ОбработкаПолученияПредставления(Представление, СтандартнаяОбработка)\n' +
          '|  СтандартнаяОбработка = Ложь;\n' +
          '|  Представление = ""НекийКласс"";\n' +
          '|КонецПроцедуры"; ' +
          'С = ЗагрузитьСценарийИзСтроки(Текст); ' +
          'сообщить(Строка(С));',
      ),
    ).toEqual(['НекийКласс']);
  });

  it('у загруженного сценария можно вызвать экспортный метод', () => {
    expect(
      exec(
        'Текст = "Функция Удвоить(Знач Ч) Экспорт\n|  Возврат Ч * 2;\n|КонецФункции"; ' +
          'С = ЗагрузитьСценарийИзСтроки(Текст); ' +
          'сообщить(С.Удвоить(21));',
      ),
    ).toEqual(['42']);
  });

  it('ТекущийСценарий возвращает Сценарий', () => {
    expect(exec('С = ТекущийСценарий(); сообщить(ТипЗнч(С) = Тип("Сценарий"));')).toEqual(['Истина']);
  });
});
