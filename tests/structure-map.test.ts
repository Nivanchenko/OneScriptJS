import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('Структура и Соответствие', () => {
  afterEach(() => vi.restoreAllMocks());

  it('Структура: создание по ключам/значениям и доступ по ключу', () => {
    expect(exec('С = Новый Структура("Ключ1,Ключ2", "Знач1", "Знач2"); сообщить(С.Ключ1); сообщить(С.Количество());')).toEqual([
      'Знач1',
      '2',
    ]);
  });

  it('Структура: Вставить и Свойство', () => {
    expect(exec('С = Новый Структура; С.Вставить("А", 1); сообщить(С.Свойство("А")); сообщить(С.А);')).toEqual(['Истина', '1']);
  });

  it('Структура: присваивание значения по ключу', () => {
    expect(exec('С = Новый Структура("Ключ"); С.Ключ = 42; сообщить(С.Ключ);')).toEqual(['42']);
  });

  it('Соответствие: Вставить и индексация', () => {
    expect(exec('С = Новый Соответствие; С.Вставить("А", 1); С["Б"] = 2; сообщить(С["А"]); сообщить(С["Б"]);')).toEqual(['1', '2']);
  });

  it('Соответствие: Получить и Количество', () => {
    expect(exec('С = Новый Соответствие; С.Вставить("А", 1); сообщить(С.Получить("А")); сообщить(С.Количество());')).toEqual(['1', '1']);
  });

  it('ФиксированнаяСтруктура только для чтения', () => {
    expect(() => exec('С = Новый ФиксированнаяСтруктура("Ключ", "Знач"); С.Ключ = 1;')).toThrow(/только для чтения/);
  });

  it('ФиксированныйМассив только для чтения', () => {
    expect(() => exec('М = Новый ФиксированныйМассив(Новый Массив(1)); М[0] = 2;')).toThrow(/только для чтения/);
  });

  it('Для Каждого по Структуре — ключи', () => {
    expect(exec('С = Новый Структура("А,Б", 1, 2); Для Каждого К Из С Цикл сообщить(К); КонецЦикла;')).toEqual(['а', 'б']);
  });

  it('ПрочитатьJSON объекта → Структура', () => {
    expect(exec('С = ПрочитатьJSON("{""a"":1}"); сообщить(С.a);')).toEqual(['1']);
  });

  it('ЗаписатьJSON структуры → объект', () => {
    expect(exec('С = Новый Структура("a", 1); сообщить(ЗаписатьJSON(С));')).toEqual(['{"a":1}']);
  });

  it('отсутствующий ключ Структуры бросает (как в 1С)', () => {
    expect(() => exec('С = Новый Структура; сообщить(С.НетКлюча);')).toThrow(/Поле объекта не обнаружено/);
  });
});
