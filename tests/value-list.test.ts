import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('СписокЗначений', () => {
  afterEach(() => vi.restoreAllMocks());

  it('добавляет элементы и даёт доступ по индексу', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить("a"); СЗ.Добавить("b"); сообщить(СЗ.Количество()); сообщить(СЗ[0].Значение);'),
    ).toEqual(['2', 'a']);
  });

  it('хранит представление, пометку, картинку', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; Э = СЗ.Добавить(1, "представление", Истина, "картинка"); сообщить(Э.Представление); сообщить(Э.Пометка); сообщить(Э.Картинка);'),
    ).toEqual(['представление', 'Истина', 'картинка']);
  });

  it('Индекс элемента и НайтиПоЗначению', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить(1); СЗ.Добавить(2); сообщить(СЗ.Индекс(СЗ[1])); сообщить(СЗ.НайтиПоЗначению(2).Значение); сообщить(СЗ.НайтиПоЗначению(9) = Неопределено);'),
    ).toEqual(['1', '2', 'Истина']);
  });

  it('сортирует по значению и представлению', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить(4,"14"); СЗ.Добавить(3,"3"); СЗ.Добавить(2,"2"); СЗ.Добавить(1,"1"); СЗ.СортироватьПоЗначению(); сообщить(СЗ[0].Значение); СЗ.СортироватьПоПредставлению(); сообщить(СЗ[0].Значение);'),
    ).toEqual(['1', '1']);
  });

  it('сортирует строки по правилам 1С (строчная "а" раньше "Б")', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить("Бааааа"); СЗ.Добавить("аааааа"); СЗ.СортироватьПоЗначению(); сообщить(СЗ[0].Значение);'),
    ).toEqual(['аааааа']);
  });

  it('Строка(СписокЗначений) — элементы через "; "', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить(11); СЗ.Добавить(12,"двенадцать"); СЗ.Добавить(Неопределено); сообщить(Строка(СЗ));'),
    ).toEqual(['11; двенадцать; <Пустое значение>']);
  });

  it('Строка(элемент) с Неопределено и Null', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить(Неопределено); СЗ.Добавить(NULL); сообщить(Строка(СЗ[0])); сообщить(Строка(СЗ[1]));'),
    ).toEqual(['<Пустое значение>', '<Пустое значение>']);
  });

  it('запись по индексу — только для чтения', () => {
    expect(() => exec('СЗ = Новый СписокЗначений; СЗ.Добавить(1); СЗ[0] = СЗ[0];')).toThrow(/только для чтения/);
  });

  it('ПолучитьИдентификатор уникален и не привязан к позиции', () => {
    expect(
      exec('СЗ = Новый СписокЗначений; СЗ.Добавить(1); СЗ.Добавить(-2); СЗ.Добавить(3); СЗ.Добавить(-4); СЗ.Удалить(2); СЗ.Добавить(0); СЗ.СортироватьПоЗначению(); сообщить(СЗ[0].ПолучитьИдентификатор()); сообщить(СЗ[3].ПолучитьИдентификатор());'),
    ).toEqual(['3', '0']);
  });
});
