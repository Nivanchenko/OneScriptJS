import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('ГенераторСлучайныхЧисел', () => {
  afterEach(() => vi.restoreAllMocks());

  it('создаётся без параметров', () => {
    expect(exec('Г = Новый ГенераторСлучайныхЧисел(); сообщить(Строка(ТипЗнч(Г)));')).toEqual([
      'ГенераторСлучайныхЧисел',
    ]);
  });

  it('границы: [0..4294967295] допустимы, остальное — ошибка', () => {
    expect(
      exec(
        'Г = Новый ГенераторСлучайныхЧисел(); Г.СлучайноеЧисло(0, 4294967295); ' +
          'Ош = 0; ' +
          'Попытка Г.СлучайноеЧисло(-10, 4294967295); Исключение Ош = Ош + 1; КонецПопытки; ' +
          'Попытка Г.СлучайноеЧисло(0, 4294967296); Исключение Ош = Ош + 1; КонецПопытки; ' +
          'Попытка Г.СлучайноеЧисло(10, 5); Исключение Ош = Ош + 1; КонецПопытки; ' +
          'сообщить(Ош);',
      ),
    ).toEqual(['3']);
  });

  it('значение попадает в заданный диапазон', () => {
    expect(
      exec(
        'Г = Новый ГенераторСлучайныхЧисел(42); ' +
          'Ч = Г.СлучайноеЧисло(10, 20); сообщить(Ч >= 10 И Ч <= 20); ' +
          'Ч2 = Г.СлучайноеЧисло(7, 7); сообщить(Ч2);',
      ),
    ).toEqual(['Истина', '7']);
  });

  it('СлучайноеЧисло() без параметров возвращает целое uint32', () => {
    expect(
      exec(
        'Г = Новый ГенераторСлучайныхЧисел(1); ' +
          'Ч = Г.СлучайноеЧисло(); сообщить(Ч >= 0 И Ч <= 4294967295); сообщить(Ч = Цел(Ч));',
      ),
    ).toEqual(['Истина', 'Истина']);
  });

  it('детерминизм: одинаковый seed даёт одинаковую последовательность', () => {
    expect(
      exec(
        'Г1 = Новый ГенераторСлучайныхЧисел(123); Г2 = Новый ГенераторСлучайныхЧисел(123); ' +
          'сообщить(Г1.СлучайноеЧисло() = Г2.СлучайноеЧисло()); ' +
          'сообщить(Г1.СлучайноеЧисло(100, 200) = Г2.СлучайноеЧисло(100, 200));',
      ),
    ).toEqual(['Истина', 'Истина']);
  });

  it('огромные и дробные seed детерминированы', () => {
    expect(
      exec(
        'А = Новый ГенераторСлучайныхЧисел(-36893488147419103232); Б = Новый ГенераторСлучайныхЧисел(-36893488147419103232); ' +
          'сообщить(А.СлучайноеЧисло() = Б.СлучайноеЧисло()); ' +
          'В = Новый ГенераторСлучайныхЧисел(36893488147419103.232); Г = Новый ГенераторСлучайныхЧисел(36893488147419103.232); ' +
          'сообщить(В.СлучайноеЧисло() = Г.СлучайноеЧисло());',
      ),
    ).toEqual(['Истина', 'Истина']);
  });
});
