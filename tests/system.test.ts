import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('системная информация и переменные среды', () => {
  afterEach(() => vi.restoreAllMocks());

  it('ПустаяСтрока распознаёт пустые и пробельные строки', () => {
    expect(exec('сообщить(ПустаяСтрока("")); сообщить(ПустаяСтрока("   ")); сообщить(ПустаяСтрока("x"));')).toEqual([
      'Истина',
      'Истина',
      'Ложь',
    ]);
  });

  it('ПеременныеСреды возвращает непустое соответствие', () => {
    expect(exec('П = ПеременныеСреды(); сообщить(П.Количество() > 0);')).toEqual(['Истина']);
  });

  it('Получить/УстановитьПеременнуюСреды', () => {
    expect(
      exec('УстановитьПеременнуюСреды("ONSCRIPT_TEST_VAR", "значение"); сообщить(ПолучитьПеременнуюСреды("ONSCRIPT_TEST_VAR"));'),
    ).toEqual(['значение']);
  });

  it('СистемнаяИнформация: базовые свойства', () => {
    expect(
      exec(
        'Си = Новый СистемнаяИнформация(); ' +
          'сообщить(ПустаяСтрока(Си.Версия)); ' +
          'сообщить(Си.КоличествоПроцессоров > 0); ' +
          'сообщить(ТипЗнч(Си.Это64БитнаяОперационнаяСистема) = Тип("Булево")); ' +
          'сообщить(ПустаяСтрока(Си.ВерсияОС));',
      ),
    ).toEqual(['Ложь', 'Истина', 'Истина', 'Ложь']);
  });

  it('СистемнаяИнформация.ПолучитьПутьПапки для профиля пользователя', () => {
    expect(
      exec('Си = Новый СистемнаяИнформация(); сообщить(ПустаяСтрока(Си.ПолучитьПутьПапки(СпециальнаяПапка.ПрофильПользователя)));'),
    ).toEqual(['Ложь']);
  });
});
