import { describe, expect, it } from 'vitest';
import { runWithModules } from './helpers/module-fixtures';

const KLASS = '/app/lib/Класс.os';

const CLASS_SOURCE = [
  'Перем Значение Экспорт;',
  'Перем Счётчик;',
  '',
  'Процедура ПриСозданииОбъекта(Обязательный, Необязательный = "по умолчанию")',
  '  Значение = Обязательный + "/" + Необязательный;',
  '  Счётчик = 0;',
  'КонецПроцедуры',
  '',
  'Функция Увеличить() Экспорт',
  '  Счётчик = Счётчик + 1;',
  '  Возврат Счётчик;',
  'КонецФункции',
].join('\n');

describe('импорт класса (#Использовать)', () => {
  it('создаёт экземпляры с аргументами и значением по умолчанию', () => {
    const logs = runWithModules(
      [
        '#Использовать "lib/Класс.os"',
        'А = Новый Класс("раз");',
        'Б = Новый Класс("два", "три");',
        'Сообщить(А.Значение);',
        'Сообщить(Б.Значение);',
      ].join('\n'),
      { [KLASS]: CLASS_SOURCE },
    );
    expect(logs).toEqual(['раз/по умолчанию', 'два/три']);
  });

  it('держит независимое состояние экземпляров', () => {
    const logs = runWithModules(
      [
        '#Использовать "lib/Класс.os"',
        'А = Новый Класс("а");',
        'Б = Новый Класс("б");',
        'Сообщить(А.Увеличить());',
        'Сообщить(А.Увеличить());',
        'Сообщить(Б.Увеличить());',
      ].join('\n'),
      { [KLASS]: CLASS_SOURCE },
    );
    expect(logs).toEqual(['1', '2', '1']);
  });

  it('исполняет тело класса на каждый экземпляр до конструктора', () => {
    const logs = runWithModules(
      [
        '#Использовать "lib/Класс.os"',
        'А = Новый Класс("а");',
        'Б = Новый Класс("б");',
      ].join('\n'),
      {
        [KLASS]: [
          'Процедура ПриСозданииОбъекта(Имя)',
          '  Сообщить("конструктор " + Имя);',
          'КонецПроцедуры',
          'Сообщить("тело");',
        ].join('\n'),
      },
    );
    expect(logs).toEqual(['тело', 'конструктор а', 'тело', 'конструктор б']);
  });

  it('не даёт вызвать конструктор снаружи', () => {
    expect(() =>
      runWithModules(
        '#Использовать "lib/Класс.os"\nА = Новый Класс("а");\nА.ПриСозданииОбъекта("б");',
        { [KLASS]: CLASS_SOURCE },
      ),
    ).toThrow("Метод 'ПриСозданииОбъекта' не найден");
  });

  it('запрещает использовать класс как модуль', () => {
    expect(() =>
      runWithModules('#Использовать "lib/Класс.os"\nСообщить(Класс.Значение);', {
        [KLASS]: CLASS_SOURCE,
      }),
    ).toThrow("Класс 'Класс' не является модулем");
  });

  it('сообщает о неверной арности конструктора', () => {
    expect(() =>
      runWithModules('#Использовать "lib/Класс.os"\nА = Новый Класс();', {
        [KLASS]: CLASS_SOURCE,
      }),
    ).toThrow('необходимых параметров: 1, передано параметров: 0');
    expect(() =>
      runWithModules('#Использовать "lib/Класс.os"\nА = Новый Класс("а", "б", "в");', {
        [KLASS]: CLASS_SOURCE,
      }),
    ).toThrow('необходимых параметров: 1, передано параметров: 3');
  });

  it('сообщает тип экземпляра как имя класса', () => {
    const logs = runWithModules(
      '#Использовать "lib/Класс.os"\nА = Новый Класс("а");\nСообщить(ТипЗнч(А) = Тип("Класс"));',
      { [KLASS]: CLASS_SOURCE },
    );
    expect(logs).toEqual(['Истина']);
  });
});
