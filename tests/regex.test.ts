import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('РегулярноеВыражение', () => {
  afterEach(() => vi.restoreAllMocks());

  it('создаётся и имеет правильный тип', () => {
    expect(exec('Р = Новый РегулярноеВыражение("a"); сообщить(Строка(ТипЗнч(Р)));')).toEqual(['РегулярноеВыражение']);
  });

  it('Совпадает', () => {
    expect(
      exec('Р = Новый РегулярноеВыражение("\\d\\d"); сообщить(Р.Совпадает("15")); сообщить(Р.Совпадает("q"));'),
    ).toEqual(['Истина', 'Ложь']);
  });

  it('ИгнорироватьРегистр по умолчанию Истина и переключается', () => {
    expect(
      exec(
        'Р = Новый РегулярноеВыражение("S"); сообщить(Р.ИгнорироватьРегистр); сообщить(Р.Совпадает("s")); ' +
          'Р.ИгнорироватьРегистр = Ложь; сообщить(Р.ИгнорироватьРегистр); сообщить(Р.Совпадает("s"));',
      ),
    ).toEqual(['Истина', 'Истина', 'Ложь', 'Ложь']);
  });

  it('Многострочный по умолчанию Истина', () => {
    expect(
      exec('Р = Новый РегулярноеВыражение("^S"); С = "S" + Символы.ПС + "s"; сообщить(Р.НайтиСовпадения(С).Количество());'),
    ).toEqual(['2']);
  });

  it('НайтиСовпадения: количество, Значение/Индекс/Длина', () => {
    expect(
      exec(
        'Р = Новый РегулярноеВыражение("\\d\\d\\d"); К = Р.НайтиСовпадения("s456"); сообщить(К.Количество()); ' +
          'С = К[0]; сообщить(С.Значение); сообщить(С.Индекс); сообщить(С.Длина);',
      ),
    ).toEqual(['1', '456', '1', '3']);
  });

  it('вложенные группы: значения, индексы, длины, имена', () => {
    expect(
      exec(
        'Р = Новый РегулярноеВыражение("(\\d)(\\d\\d)"); С = Р.НайтиСовпадения("s456")[0]; Г = С.Группы; ' +
          'сообщить(Г.Количество()); сообщить(Г[0].Значение); сообщить(Г[1].Значение); сообщить(Г[1].Индекс); ' +
          'сообщить(Г[2].Значение); сообщить(Г[2].Длина); сообщить(Г[1].Имя);',
      ),
    ).toEqual(['3', '456', '4', '1', '56', '2', '1']);
  });

  it('именованные группы нумеруются после безымянных (как в .NET)', () => {
    expect(
      exec(
        'Р = Новый РегулярноеВыражение("(\\d)(?<myname>\\d)(\\d)"); Г = Р.НайтиСовпадения("s123")[0].Группы; ' +
          'сообщить(Г[1].Значение); сообщить(Г[2].Значение); сообщить(Г[3].Значение); ' +
          'сообщить(Г[1].Имя); сообщить(Г[2].Имя); сообщить(Г[3].Имя); ' +
          'сообщить(Г.ПоИмени("myname").Значение);',
      ),
    ).toEqual(['1', '3', '2', '1', '2', 'myname', '2']);
  });

  it('Разделить', () => {
    expect(
      exec('Р = Новый РегулярноеВыражение("\\s"); М = Р.Разделить("4 5"); сообщить(М.Количество()); сообщить(М[0]); сообщить(М[1]);'),
    ).toEqual(['2', '4', '5']);
  });

  it('Заменить с обратными ссылками', () => {
    expect(
      exec('Р = Новый РегулярноеВыражение("(\\d)(\\d)(\\d)"); сообщить(Р.Заменить("456", "$3$2$1"));'),
    ).toEqual(['654']);
  });

  it('обход коллекции совпадений работает', () => {
    expect(
      exec('Р = Новый РегулярноеВыражение("\\d"); К = Р.НайтиСовпадения("1a2"); Для Каждого С Из К Цикл сообщить(С.Значение); КонецЦикла;'),
    ).toEqual(['1', '2']);
  });
});
