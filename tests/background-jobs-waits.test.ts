import { describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';
import { isThenable } from '../src/runtime/async';

async function execute(source: string): Promise<string[]> {
  const logs: string[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(args.map((a) => String(a)).join(' '));
  });
  try {
    const returned = run(source, createGlobalContext());
    if (isThenable(returned)) await returned;
    return logs;
  } finally {
    spy.mockRestore();
  }
}

const HELPERS = `
  Функция Арг(Знач Значение) Экспорт
    Результат = Новый Массив;
    Результат.Добавить(Значение);
    Возврат Результат;
  КонецФункции

  Процедура Упасть() Экспорт
    Приостановить(10);
    ВызватьИсключение "авария";
  КонецПроцедуры

  Процедура Пауза(Знач Мс) Экспорт
    Приостановить(Мс);
  КонецПроцедуры
`;

describe('фоновые задания: User Story 2 (ожидания)', () => {
  it('ОжидатьВсе ждёт все задания и возвращает Истина', async () => {
    const logs = await execute(`
      ${HELPERS}
      Задания = Новый Массив;
      Задания.Добавить(ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(20)));
      Задания.Добавить(ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(40)));
      Сообщить(ФоновыеЗадания.ОжидатьВсе(Задания));
      Для Каждого Задание Из Задания Цикл
        Сообщить(Задание.Состояние);
      КонецЦикла;
    `);
    expect(logs).toEqual(['Истина', 'Завершено', 'Завершено']);
  });

  it('ОжидатьВсе по таймауту возвращает Ложь и не отменяет задания', async () => {
    const logs = await execute(`
      ${HELPERS}
      Задание = ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(60));
      Задания = Новый Массив;
      Задания.Добавить(Задание);
      Сообщить(ФоновыеЗадания.ОжидатьВсе(Задания, 5));
      Сообщить(Задание.ОжидатьЗавершения());
      Сообщить(Задание.Состояние);
    `);
    expect(logs).toEqual(['Ложь', 'Истина', 'Завершено']);
  });

  it('ОжидатьЛюбое возвращает индекс завершившегося задания', async () => {
    const logs = await execute(`
      ${HELPERS}
      Задания = Новый Массив;
      Задания.Добавить(ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(20)));
      Задания.Добавить(ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(80)));
      Сообщить(ФоновыеЗадания.ОжидатьЛюбое(Задания));
    `);
    expect(logs).toEqual(['0']);
  });

  it('ОжидатьЗавершенияЗадач бросает исключение при аварийных заданиях', async () => {
    const logs = await execute(`
      ${HELPERS}
      ФоновыеЗадания.Выполнить(ЭтотОбъект, "Упасть");
      ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(10));
      Попытка
        ФоновыеЗадания.ОжидатьЗавершенияЗадач();
        Сообщить("без ошибки");
      Исключение
        Сообщить("перехвачено");
      КонецПопытки;
      Осталось = ФоновыеЗадания.ПолучитьФоновыеЗадания();
      Сообщить(Осталось.Количество());
    `);
    // При аварии задания из реестра не удаляются.
    expect(logs).toEqual(['перехвачено', '2']);
  });

  it('после успешного ОжидатьЗавершенияЗадач задания удаляются из реестра', async () => {
    const logs = await execute(`
      ${HELPERS}
      ФоновыеЗадания.Выполнить(ЭтотОбъект, "Пауза", Арг(10));
      ФоновыеЗадания.ОжидатьЗавершенияЗадач();
      Сообщить(ФоновыеЗадания.ПолучитьФоновыеЗадания().Количество());
    `);
    expect(logs).toEqual(['0']);
  });

  it('пустые массивы и неверные аргументы', async () => {
    const logs = await execute(`
      Пусто = Новый Массив;
      Сообщить(ФоновыеЗадания.ОжидатьВсе(Пусто));
      Попытка
        ФоновыеЗадания.ОжидатьЛюбое(Пусто);
        Сообщить("без ошибки");
      Исключение
        Сообщить("перехвачено");
      КонецПопытки;
      Попытка
        ФоновыеЗадания.ОжидатьВсе(Новый Массив, -1);
        Сообщить("без ошибки");
      Исключение
        Сообщить("перехвачено");
      КонецПопытки;
    `);
    expect(logs).toEqual(['Истина', 'перехвачено', 'перехвачено']);
  });
});
