import { afterEach, describe, expect, it, vi } from 'vitest';
import { run } from '../src/runtime/runner';
import { createGlobalContext } from '../src/stdlib/global-context';

function exec(source: string): unknown[] {
  const logs: unknown[] = [];
  const spy = vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
    logs.push(...args);
  });
  try {
    run(source, createGlobalContext());
  } finally {
    spy.mockRestore();
  }
  return logs;
}

describe('параметры по ссылке / Знач', () => {
  afterEach(() => vi.restoreAllMocks());

  it('по ссылке: метод меняет переменную вызывающего', () => {
    expect(
      exec('Процедура Инкремент(Парам)\n  Парам = Парам + 1;\nКонецПроцедуры\nx = 5;\nИнкремент(x);\nсообщить(x);'),
    ).toEqual(['6']);
  });

  it('Знач — по значению: не меняет вызывающего', () => {
    expect(
      exec('Процедура НеМеняет(Знач Парам)\n  Парам = 99;\nКонецПроцедуры\nx = 5;\nНеМеняет(x);\nсообщить(x);'),
    ).toEqual(['5']);
  });

  it('по ссылке на элемент массива', () => {
    expect(
      exec('Процедура Установить(Значение)\n  Значение = "изменено";\nКонецПроцедуры\nМ = Новый Массив; М.Добавить("оригинал");\nУстановить(М[0]);\nсообщить(М[0]);'),
    ).toEqual(['изменено']);
  });

  it('по ссылке на свойство структуры', () => {
    expect(
      exec('Процедура Установить(Значение)\n  Значение = 42;\nКонецПроцедуры\nС = Новый Структура("Ключ", 0);\nУстановить(С.Ключ);\nсообщить(С.Ключ);'),
    ).toEqual(['42']);
  });

  it('по ссылке с литералом — изменение отбрасывается', () => {
    expect(
      exec('Процедура Установить(Значение)\n  Значение = 1;\n  сообщить(Значение);\nКонецПроцедуры\nУстановить(5);'),
    ).toEqual(['1']);
  });

  it('по ссылке на модульную переменную (Перем)', () => {
    expect(
      exec('Перем Счётчик;\nПроцедура Увеличить(Значение)\n  Значение = Значение + 1;\nКонецПроцедуры\nСчётчик = 10;\nУвеличить(Счётчик);\nсообщить(Счётчик);'),
    ).toEqual(['11']);
  });
});
