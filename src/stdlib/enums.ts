import type { GlobalContext } from '../runtime/context';
import { BslConstants, BslEnumNamespace } from '../runtime/enum';

function registerEnum(
  ctx: GlobalContext,
  typeName: string,
  ruGlobal: string,
  enGlobal: string,
  values: Record<string, string>,
): void {
  const ns = new BslEnumNamespace(typeName, values);
  ctx.registerGlobal(ruGlobal, ns);
  ctx.registerGlobal(enGlobal, ns);
}

